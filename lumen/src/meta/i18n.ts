export type StrKey = keyof typeof PL;
let current: Lang = 'pl';

export function setLang(l: Lang): void {
  current = l;
  document.documentElement.lang = l;
}

export function lang(): Lang {
  return current;
}

export function t(k: StrKey): string {
  return (current === 'pl' ? PL : EN)[k];
}

